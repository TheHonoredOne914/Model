#!/usr/bin/env python3
"""Generate src/data/videos.ts from oEmbed-verified video results.
268 verified direct links, 92 concepts, 3 teachers per concept."""
import json

rows = json.load(open("/home/z/my-project/scripts/v3/vid_verified.json"))
ok = [r for r in rows if r["ok"]]

PREF = ["Physics Wallah", "Alakh Pandey", "Magnet Brains", "Shobhit Nirwan", "Digraj Singh Rajput",
        "PW Class 9", "PW Class 10", "PW Foundation", "Vedantu", "BYJU", "Sunlike study",
        "Social School", "Prashant Kirad", "Science and Fun", "Ashu Ghai", "Khan Academy",
        "LearnoHub", "Grade booster", "Amit Sengupta", "Class 9 Learn", "2Pi", "Samridhi"]

def key(r):
    a = r["author"]
    for i, p in enumerate(PREF):
        if p.lower() in a.lower():
            return (i, -len(a))
    return (len(PREF), 0)

by_concept = {}
for r in ok:
    by_concept.setdefault((r["subj"], r["cls"], r["concept"]), []).append(r)

SUBJ_NAME = {"math": "Maths", "sci": "Science", "sst": "SST"}

out = []
out.append("""// Saathy curated video kit — 92 concepts x ~3 teachers, ALL links oEmbed-verified live.
// Generated by scripts/v3/gen_videos_ts.py from verified YouTube results (no invented IDs).
// Primary video first per concept; alternates let students pick the teacher that clicks.

export interface VideoEntry {
  vid: string;
  author: string;
  title: string;
}

export interface VideoConcept {
  subject: "math" | "sci" | "sst";
  subjectName: string;
  cls: number;
  concept: string;
  primary: VideoEntry;
  alternates: VideoEntry[];
  watchUrl: (vid: string) => string;
}

/** Honest auto watch-plan: relative checkpoints (we never invent mm:ss). */
export const AUTO_PLAN: [string, string][] = [
  ["0:00", "Hook & why this matters"],
  ["~20% in", "Basics: the words and the first example"],
  ["~50% in", "Core concept — watch actively, pause + note"],
  ["~75% in", "Worked examples & NCERT questions"],
  ["end", "Recap — then take the Saathy quiz"],
];

export function watchUrl(vid: string): string {
  return `https://www.youtube.com/watch?v=${vid}`;
}
""")

out.append("const DB: Array<[VideoConcept[\"subject\"], number, string, VideoEntry[]]> = [")
for (subj, cls, concept), vids in sorted(by_concept.items(), key=lambda kv: (kv[0][0], kv[0][1], kv[0][2].lower())):
    vids = sorted(vids, key=key)
    entries = ", ".join(
        json.dumps({"vid": v["vid"], "author": v["author"][:48], "title": v["title"][:110]}, ensure_ascii=False)
        for v in vids)
    out.append(f'  ["{subj}",{cls},{json.dumps(concept, ensure_ascii=False)},[{entries}]],')
out.append("];")
out.append("""
export const VIDEO_KIT: VideoConcept[] = DB.map(([subject, cls, concept, vids]) => ({
  subject,
  subjectName: SUBJ_NAME[subject],
  cls,
  concept,
  primary: vids[0],
  alternates: vids.slice(1),
  watchUrl,
}));

const SUBJ_NAME: Record<VideoConcept["subject"], string> = { math: "Maths", sci: "Science", sst: "SST" };

/** Token-overlap match of a chat topic to the video kit. Returns best concepts. */
export function matchVideos(topic: string, opts?: { cls?: number; limit?: number }): VideoConcept[] {
  const t = topic.toLowerCase().replace(/[^a-z0-9 ]/g, " ");
  const words = t.split(/\\s+/).filter((w) => w.length > 2);
  if (!words.length) return [];
  const scored = VIDEO_KIT.map((v) => {
    const c = v.concept.toLowerCase();
    let s = 0;
    for (const w of words) if (c.includes(w)) s += w.length >= 5 ? 2 : 1;
    if (c === t.trim()) s += 6;
    if (opts?.cls && v.cls === opts.cls) s += 0.5;
    return { v, s };
  }).filter((x) => x.s >= 2);
  scored.sort((a, b) => b.s - a.s);
  return scored.slice(0, opts?.limit ?? 3).map((x) => x.v);
}

/** Compact block injected into the system prompt so Saathy only ever suggests verified links. */
export function videoGroundingBlock(topic: string, cls?: number): { text: string; concept: string } | null {
  const hits = matchVideos(topic, { cls, limit: 1 });
  const h = hits[0];
  if (!h) return null;
  const lines = [
    `VERIFIED VIDEO SUGGESTIONS for "${h.concept}" (Class ${h.cls} ${h.subjectName}) — give these EXACT links, never invent video IDs or timestamps:`,
    `- Primary: ${h.primary.title} — ${h.primary.author}: ${watchUrl(h.primary.vid)}`,
    ...h.alternates.map((a) => `- Alternate: ${a.title} — ${a.author}: ${watchUrl(a.vid)}`),
    `- Watch plan: 0:00 hook, ~20% basics, ~50% core idea, ~75% worked examples, end recap (the video's own YouTube chapters allow precise jumps).`,
  ];
  return { text: lines.join("\\n"), concept: h.concept };
}

export const VIDEO_KIT_SUMMARY = { concepts: VIDEO_KIT.length, links: DB.reduce((n, d) => n + d[3].length, 0) };
""")

src = "\n".join(out)
open("/home/z/my-project/src/data/videos.ts", "w", encoding="utf-8").write(src)
print(f"wrote src/data/videos.ts ({len(src)//1024} KB), concepts={len(by_concept)}, links={sum(len(v) for v in by_concept.values())}")
